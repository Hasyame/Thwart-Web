const cards = JSON.parse(readFileSync(new URL('../public/data/cards/en/aoa.json', import.meta.url), 'utf8'));
for (const expert of [false,true]) for (const players of [1,2,3,4]) {
  const setup = withVillainOrder(setupFor(cards.filter(c=>c.card_set_code==='four_horsemen'),players,expert),['45084a','45082a','45081a','45083a']);
  assert.equal(setup.villain.length,1);
  assert.equal(setup.moreVillains.length,3);
  assert.equal(setup.villain[0].code,expert?'45084b':'45084a');
  let table=withActiveVillain(startOf(setup),2);
  table=damagedAt(table,1,3);
  assert.equal(villainDamageAt(table,0),0);
  assert.equal(villainDamageAt(table,1),3);
  table=damagedAt(table,0,999);
  assert.equal(villainDefeated(table),false);
  for(let track=1;track<4;track++) table=damagedAt(table,track,999);
  assert.equal(villainDefeated(table),true);
  assert.equal(JSON.parse(JSON.stringify(table)).progress.activeVillain,2);
  const formSetup=setupFor(cards.filter(c=>c.card_set_code==='en_sabah_nur'),players,expert);
  assert.equal(formSetup.villain.length,2);
  assert.equal(formSetup.villainForms[0].length,3);
  let forms=withVillainForm(damagedAt(startOf(formSetup),0,4),2);
  assert.equal(forms.progress.damage,4);
  assert.equal(villainSideOf(forms).code,expert?'45185c':'45184c');
  forms=villainAdvanced(forms);
  assert.equal(forms.progress.damage,0);
  assert.equal(forms.progress.villainForm,0);
  const apoc=setupFor(cards.filter(c=>c.card_set_code==='apocalypse'),players,expert);
  assert.equal(villainSideOf(startOf(apoc)).stage,expert?'III':'II');
}
